const STORAGE_KEY = 'jobs-board-user-jobs';

function loadUserJobs(): Job[] {
  try {
    const raw = localStorage.getItem(STORAGE_KEY);
    return raw ? JSON.parse(raw) : [];
  } catch {
    return [];
  }
}

function saveUserJobs(userJobs: Job[]) {
  localStorage.setItem(STORAGE_KEY, JSON.stringify(userJobs));
}

export function addJob(job: Job) {
  const userJobs = loadUserJobs();
  userJobs.unshift(job);
  saveUserJobs(userJobs);
}

export function getAllJobs(): Job[] {
  const userJobs = loadUserJobs();
  return [...userJobs, ...staticJobs];
}

